"""
task_body.py
------------
One place that decides what a Microsoft To Do task's description says.

Both tools that create tasks - the morning briefing and inbox_actions - were
writing their own one-line body into the same Graph field, from different
code, with different fields available. This is the shared piece: each caller
hands over whatever it knows and gets back the same shape.

The body is deliberately plain text. To Do renders the body as plain text on
every client, so markdown just shows its own punctuation, and a long URL on
its own line is clickable in the apps that linkify.

The [src:...] marker at the end is load-bearing, not decoration: it is how a
completed task suppresses the same action tomorrow. The action's wording is
regenerated by the model on every run, so the id of the email it came from is
the only stable key.
"""

MAX_SUMMARY = 600
MAX_CONTEXT = 300


def _clean(v) -> str:
    return " ".join(str(v or "").split()).strip()


def build(summary: str = "", context: str = "", from_name: str = "",
          subject: str = "", when: str = "", deadline: str = "",
          topic: str = "", link: str = "", msg_id: str = "") -> str:
    """
    Returns the task body. Every field is optional - a caller that knows only
    the context still gets a sensible one-liner, which is what the briefing
    produced before and what a task created from a thin source still gets.
    """
    summary, context = _clean(summary)[:MAX_SUMMARY], _clean(context)[:MAX_CONTEXT]

    out = []
    if summary:
        out.append(summary)
    # Only repeat the one-line context when it is not already the summary -
    # the briefing's old body WAS the context, so without this check every
    # task would say the same thing twice.
    if context and context.lower() not in summary.lower():
        out.append(context if not summary else f"Context: {context}")

    facts = []
    src = " · ".join(x for x in (_clean(from_name), _clean(subject)) if x)
    if src:
        facts.append(f"From: {src}")
    if _clean(when):
        facts.append(f"Received: {_clean(when)}")
    if _clean(deadline):
        facts.append(f"Due: {_clean(deadline)}")
    if _clean(topic):
        facts.append(f"Topic: {_clean(topic)}")
    if facts:
        out.append("\n".join(facts))

    if _clean(link):
        out.append(f"Open the email: {_clean(link)}")
    if _clean(msg_id):
        out.append(f"[src:{_clean(msg_id)}]")

    return "\n\n".join(out)


def pretty_when(ts: str) -> str:
    """'2026-10-09T06:41:00Z' -> 'Thu 9 Oct 2026, 6:41am'. Falls back to the
    raw string, because an unparseable date is still better than none."""
    import datetime
    raw = str(ts or "").strip()
    if not raw:
        return ""
    # A date with no time ("2026-10-09") must not gain a spurious "12:00am" -
    # inbox_actions records email_date to the day, the briefing to the second.
    date_only = len(raw) <= 10 or "T" not in raw
    try:
        d = datetime.datetime.fromisoformat(raw.replace("Z", "+00:00"))
        if d.tzinfo is not None:
            d = d.astimezone(datetime.timezone(datetime.timedelta(hours=10)))
        stamp = d.strftime(f"%a {d.day} %b %Y")
        if date_only:
            return stamp
        return stamp + ", " + d.strftime("%I:%M%p").lstrip("0").lower()
    except Exception:
        return raw[:16].replace("T", " ")
